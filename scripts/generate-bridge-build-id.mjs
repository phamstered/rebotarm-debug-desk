/**
 * Generate a shared Bridge build id for C++ hello and the desk expected constants.
 * Source of truth: package.xml version + short content hash of bridge/easy_debug_bridge
 * sources (excluding generated bridge_build_id.hpp / any build trees).
 *
 * Usage: node scripts/generate-bridge-build-id.mjs [--check]
 *   --check  exit 1 if committed outputs are stale (optional CI guard)
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
export const projectRoot = resolve(dirname(scriptPath), "..");
const packageRoot = join(projectRoot, "bridge", "easy_debug_bridge");
const packageXmlPath = join(packageRoot, "package.xml");
const headerPath = join(packageRoot, "include", "easy_debug_bridge", "bridge_build_id.hpp");
const tsPath = join(projectRoot, "src", "bridgeVersion.ts");

const SKIP_DIR_NAMES = new Set(["build", "install", "log", ".git", "node_modules"]);
const SKIP_FILE_NAMES = new Set(["bridge_build_id.hpp"]);

/** @param {string} xml */
export function parsePackageVersion(xml) {
  const match = /<version>\s*([^<]+?)\s*<\/version>/i.exec(xml);
  if (!match) throw new Error("package.xml missing <version>");
  const version = match[1].trim();
  if (!/^\d+\.\d+\.\d+/.test(version)) throw new Error(`Unexpected package version: ${version}`);
  return version;
}

/**
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
async function listSourceFiles(dir) {
  /** @type {string[]} */
  const files = [];
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith(".")) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIR_NAMES.has(entry.name)) continue;
      files.push(...(await listSourceFiles(full)));
      continue;
    }
    if (!entry.isFile()) continue;
    if (SKIP_FILE_NAMES.has(entry.name)) continue;
    files.push(full);
  }
  return files;
}

/** Content hash of Bridge package sources (12 hex chars). */
export async function readBridgeBuildId(root = packageRoot) {
  const files = (await listSourceFiles(root)).sort((a, b) => a.localeCompare(b));
  if (files.length === 0) throw new Error(`No source files under ${root}`);
  const hash = createHash("sha256");
  for (const file of files) {
    const rel = relative(root, file).split("\\").join("/");
    hash.update(rel);
    hash.update("\0");
    hash.update(await readFile(file));
    hash.update("\0");
  }
  return hash.digest("hex").slice(0, 12);
}

/** @param {{ version: string, buildId: string }} info */
export function renderCppHeader({ version, buildId }) {
  return `// Generated by scripts/generate-bridge-build-id.mjs — do not edit by hand.
#pragma once

#define EASY_DEBUG_BRIDGE_VERSION "${version}"
#define EASY_DEBUG_BRIDGE_BUILD_ID "${buildId}"
`;
}

/** @param {{ version: string, buildId: string }} info */
export function renderTsModule({ version, buildId }) {
  return `/** Generated by scripts/generate-bridge-build-id.mjs — do not edit by hand. */
export const EXPECTED_BRIDGE_VERSION = "${version}";
export const EXPECTED_BRIDGE_BUILD_ID = "${buildId}";
`;
}

/**
 * @param {{ write?: boolean }} [options]
 * @returns {Promise<{ version: string, buildId: string, headerPath: string, tsPath: string, header: string, ts: string }>}
 */
export async function generateBridgeBuildId(options = {}) {
  const write = options.write !== false;
  const xml = await readFile(packageXmlPath, "utf8");
  const version = parsePackageVersion(xml);
  const buildId = await readBridgeBuildId();
  const header = renderCppHeader({ version, buildId });
  const ts = renderTsModule({ version, buildId });
  if (write) {
    await writeFile(headerPath, header, "utf8");
    await writeFile(tsPath, ts, "utf8");
  }
  return { version, buildId, headerPath, tsPath, header, ts };
}

/**
 * @param {{ version: string, buildId: string, header: string, ts: string }} generated
 */
export async function assertBridgeBuildIdFresh(generated) {
  const currentHeader = await readFile(headerPath, "utf8").catch(() => "");
  const currentTs = await readFile(tsPath, "utf8").catch(() => "");
  if (currentHeader !== generated.header || currentTs !== generated.ts) {
    throw new Error(
      "Bridge build id outputs are stale. Run: node scripts/generate-bridge-build-id.mjs",
    );
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const checkOnly = process.argv.includes("--check");
  try {
    const generated = await generateBridgeBuildId({ write: !checkOnly });
    if (checkOnly) await assertBridgeBuildIdFresh(generated);
    console.log(
      `[bridge-build-id] version=${generated.version} build_id=${generated.buildId}${checkOnly ? " (ok)" : ""}`,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
